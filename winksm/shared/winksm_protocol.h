#ifndef WINKSM_PROTOCOL_H
#define WINKSM_PROTOCOL_H

#include "winksm_types.h"

#define WINKSM_IOCTL_BASE 0x800

#define CTL_CODE_WINKSM(function, method) \
    CTL_CODE(0x8000, function, method, FILE_ANY_ACCESS)

#define IOCTL_WINKSM_GET_STATUS \
    CTL_CODE_WINKSM(0x800, METHOD_BUFFERED)

#define IOCTL_WINKSM_SET_PARAMETERS \
    CTL_CODE_WINKSM(0x801, METHOD_BUFFERED)

#define IOCTL_WINKSM_START_SCAN \
    CTL_CODE_WINKSM(0x802, METHOD_BUFFERED)

#define IOCTL_WINKSM_STOP_SCAN \
    CTL_CODE_WINKSM(0x803, METHOD_BUFFERED)

#define IOCTL_WINKSM_GET_STATS \
    CTL_CODE_WINKSM(0x804, METHOD_BUFFERED)

#define IOCTL_WINKSM_GET_PROCESSES \
    CTL_CODE_WINKSM(0x805, METHOD_BUFFERED)

#define IOCTL_WINKSM_GET_CONTAINERS \
    CTL_CODE_WINKSM(0x806, METHOD_BUFFERED)

#define IOCTL_WINKSM_ADD_TRUSTED_PID \
    CTL_CODE_WINKSM(0x807, METHOD_BUFFERED)

#define IOCTL_WINKSM_REMOVE_TRUSTED_PID \
    CTL_CODE_WINKSM(0x808, METHOD_BUFFERED)

#define IOCTL_WINKSM_GET_VERSION \
    CTL_CODE_WINKSM(0x809, METHOD_BUFFERED)

typedef struct _WINKSM_VERSION {
    uint32_t Major;
    uint32_t Minor;
    uint32_t Build;
} WINKSM_VERSION;

typedef struct _WINKSM_PID_REQUEST {
    uint32_t ProcessId;
} WINKSM_PID_REQUEST;

typedef struct _WINKSM_STATUS_RESPONSE {
    uint32_t IsRunning;
    uint32_t ProcessCount;
    uint64_t TotalSavedBytes;
} WINKSM_STATUS_RESPONSE;

#endif /* WINKSM_PROTOCOL_H */
